"""
Shared Pydantic data models for the RescueIQ Triage Engine.

ALL outputs from the triage engine are clearly labelled
PRELIMINARY DECISION-SUPPORT ASSESSMENTS. They must never be
used as the sole basis for life-safety resource allocation.

Three model families:
  A. SeverityAssessment  – module A output
  B. DuplicateCandidate, DuplicateGroup – module B output
  C. PriorityScore  – module C output
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

# ── Shared disclaimer ──────────────────────────────────────────────────────────

PRELIMINARY_LABEL = (
    "PRELIMINARY DECISION-SUPPORT ASSESSMENT. "
    "Generated by automated rule-based and AI-assisted analysis. "
    "All outputs must be reviewed and confirmed by trained emergency personnel "
    "before informing resource allocation or field operations. "
    "Never use these scores as the sole basis for life-safety decisions."
)


# ════════════════════════════════════════════════════════════════════════════════
# Module A — Severity Assessment
# ════════════════════════════════════════════════════════════════════════════════

@dataclass
class SeverityEvidence:
    """
    A single piece of evidence contributing to the severity assessment.
    
    source  : where the evidence came from ('visual_ai', 'reporter', 'geo', 'temporal')
    signal  : human-readable description of the signal
    weight  : how much this evidence influences the final level (0.0–1.0 relative)
    value   : the raw observed value (string for display)
    """
    source: str
    signal: str
    weight: float
    value: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "source": self.source,
            "signal": self.signal,
            "weight": round(self.weight, 3),
            "value": self.value,
        }


@dataclass
class SeverityAssessment:
    """
    Module A output: preliminary severity level with evidence and uncertainty.

    level          : "Low" | "Moderate" | "High" | "Critical"
    score_0_100    : numeric representation (0=Low, 33=Moderate, 66=High, 100=Critical)
    evidence       : all contributing signals
    uncertainty    : 0.0 (highly certain) → 1.0 (very uncertain)
    uncertainty_reason : text explanation of uncertainty sources
    high_risk_flag : True when evidence is sparse but context suggests Critical
    preliminary_label : ALWAYS included
    """
    level: str                                  # Low / Moderate / High / Critical
    score_0_100: float
    evidence: List[SeverityEvidence] = field(default_factory=list)
    uncertainty: float = 0.5
    uncertainty_reason: str = ""
    high_risk_flag: bool = False
    preliminary_label: str = PRELIMINARY_LABEL

    def to_dict(self) -> Dict[str, Any]:
        return {
            "level": self.level,
            "score_0_100": round(self.score_0_100, 1),
            "evidence": [e.to_dict() for e in self.evidence],
            "uncertainty": round(self.uncertainty, 3),
            "uncertainty_reason": self.uncertainty_reason,
            "high_risk_flag": self.high_risk_flag,
            "preliminary_label": self.preliminary_label,
        }


# ════════════════════════════════════════════════════════════════════════════════
# Module B — Duplicate Detection
# ════════════════════════════════════════════════════════════════════════════════

@dataclass
class DuplicateSimilarityBreakdown:
    """Component scores for a duplicate candidate pair."""
    image_hash_similarity: float = 0.0     # dHash Hamming distance converted [0,1]
    image_embedding_similarity: float = 0.0  # CLIP cosine similarity [0,1]
    text_similarity: float = 0.0           # MiniLM cosine similarity [0,1]
    geo_proximity_score: float = 0.0       # Haversine proximity → [0,1]
    time_proximity_score: float = 0.0      # Temporal decay → [0,1]
    composite_score: float = 0.0           # Weighted combination [0,1]

    def to_dict(self) -> Dict[str, Any]:
        return {k: round(v, 4) for k, v in self.__dict__.items()}


@dataclass
class DuplicateCandidate:
    """
    A single candidate duplicate pair.

    IMPORTANT: Duplicate candidates are NEVER automatically removed.
    They are surfaced for human review only.
    """
    incident_id_a: str
    incident_id_b: str
    similarity: DuplicateSimilarityBreakdown
    recommendation: str                    # "Likely duplicate" | "Possible duplicate" | "Uncertain"
    human_review_required: bool = True     # Always True — no auto-deletion
    preliminary_label: str = PRELIMINARY_LABEL

    def to_dict(self) -> Dict[str, Any]:
        return {
            "incident_id_a": self.incident_id_a,
            "incident_id_b": self.incident_id_b,
            "similarity": self.similarity.to_dict(),
            "recommendation": self.recommendation,
            "human_review_required": self.human_review_required,
            "preliminary_label": self.preliminary_label,
        }


@dataclass
class DuplicateGroup:
    """
    A cluster of incident IDs that may describe the same event.
    All member incidents are preserved. Grouping is for display only.
    """
    group_id: str
    member_ids: List[str]
    primary_id: str                    # Highest-priority incident in the group
    max_composite_score: float
    group_label: str                   # Short description of the group
    preliminary_label: str = PRELIMINARY_LABEL

    def to_dict(self) -> Dict[str, Any]:
        return {
            "group_id": self.group_id,
            "member_ids": self.member_ids,
            "primary_id": self.primary_id,
            "max_composite_score": round(self.max_composite_score, 4),
            "group_label": self.group_label,
            "preliminary_label": self.preliminary_label,
        }


# ════════════════════════════════════════════════════════════════════════════════
# Module C — Priority Score
# ════════════════════════════════════════════════════════════════════════════════

@dataclass
class PriorityFactor:
    """One scoring dimension with its raw value, weight, and weighted contribution."""
    name: str
    raw_score: float            # Normalised 0–100
    weight: float               # Administrator-configurable fraction
    weighted_contribution: float  # raw_score × weight
    explanation: str            # Human-readable rationale for this score
    evidence: List[str] = field(default_factory=list)  # supporting facts

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "raw_score": round(self.raw_score, 1),
            "weight": round(self.weight, 4),
            "weighted_contribution": round(self.weighted_contribution, 2),
            "explanation": self.explanation,
            "evidence": self.evidence,
        }


@dataclass
class PriorityWeightConfig:
    """
    Current weight configuration for the priority engine.
    Weights must sum to 1.0. Administrators may update these via API.
    """
    weight_severity: float = 0.40
    weight_urgency: float = 0.25
    weight_impact: float = 0.20
    weight_access: float = 0.15

    def validate(self) -> None:
        total = self.weight_severity + self.weight_urgency + self.weight_impact + self.weight_access
        if abs(total - 1.0) > 0.001:
            raise ValueError(f"Priority weights must sum to 1.0, got {total:.4f}")

    def to_dict(self) -> Dict[str, Any]:
        return {
            "weight_severity": self.weight_severity,
            "weight_urgency": self.weight_urgency,
            "weight_impact": self.weight_impact,
            "weight_access": self.weight_access,
        }


@dataclass
class PriorityScore:
    """
    Module C output: configurable priority score with full factor transparency.

    priority_score      : final 0–100 score
    priority_band       : "Critical" | "High" | "Moderate" | "Low"
    factors             : per-dimension breakdown (always included)
    weight_config       : weight set used for this calculation
    high_risk_flag      : True even if confidence is low (safety catch)
    flag_reason         : why high_risk_flag was raised
    preliminary_label   : ALWAYS included
    """
    priority_score: float
    priority_band: str             # Critical / High / Moderate / Low
    factors: List[PriorityFactor] = field(default_factory=list)
    weight_config: Optional[PriorityWeightConfig] = None
    high_risk_flag: bool = False
    flag_reason: str = ""
    preliminary_label: str = PRELIMINARY_LABEL

    def to_dict(self) -> Dict[str, Any]:
        return {
            "priority_score": round(self.priority_score, 1),
            "priority_band": self.priority_band,
            "factors": [f.to_dict() for f in self.factors],
            "weight_config": self.weight_config.to_dict() if self.weight_config else None,
            "high_risk_flag": self.high_risk_flag,
            "flag_reason": self.flag_reason,
            "preliminary_label": self.preliminary_label,
        }
